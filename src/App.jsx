import { lazy, Suspense } from 'react';
import './App.css';
import { createBrowserRouter, RouterProvider } from 'react-router-dom';
import { ThemeProvider } from './context/ThemeContext';
import RootLayout from './layouts/RootLayout';
import Home from './pages/home';
import ProtectedRoute from './components/auth/ProtectedRoute';
import { DashboardProvider } from './context/dashboard/DashboardContext';
const Privacy=lazy(()=>import('./pages/privacy'));
const SignUp=lazy(()=>import('./pages/signup/SignUp'));
const Login=lazy(()=>import('./pages/login/login'));
const VerifyOtp=lazy(()=>import('./pages/signup/VerifyOtp'));
const ForgotPassword=lazy(()=>import('./pages/forgotPassword/ForgotPassword'));
const ResetPassword=lazy(()=>import('./pages/resetPassword/ResetPassword'));
const OnboardingFlow=lazy(()=>import('./pages/onboarding/OnboardingFlow'));
const DashboardLayout=lazy(()=>import('./layouts/DashBoardLayout'));
const DashboardPage=lazy(()=>import('./pages/dashboard/DashboardPage'));
const SettingsPage=lazy(()=>import('./pages/dashboard/SettingsPage'));
const PluginAccess=lazy(()=>import('./pages/dashboard/PluginAccess'));
const UsersPage=lazy(()=>import('./pages/dashboard/UsersPage'));
const NotFound=lazy(()=>import('./components/NotFound'));
const router=createBrowserRouter([{path:'/',element:<RootLayout/>,children:[{index:true,element:<Home/>},{path:'privacy',element:<Privacy/>},{path:'onboarding',element:<SignUp/>},{path:'signup',element:<SignUp/>},{path:'login',element:<Login/>},{path:'forgot-password',element:<ForgotPassword/>},{path:'reset-password',element:<ResetPassword/>},{path:'verify-otp',element:<VerifyOtp/>},{element:<ProtectedRoute/>,children:[{path:'onboardingFlow',element:<OnboardingFlow/>}]},{path:'dashboard',element:<ProtectedRoute><DashboardProvider><DashboardLayout/></DashboardProvider></ProtectedRoute>,children:[{index:true,element:<DashboardPage/>},{path:'settings',element:<SettingsPage/>},{path:'keys',element:<PluginAccess/>},{path:'users',element:<UsersPage/>}]}]},{path:'*',element:<NotFound/>}]);
export default function App(){return <ThemeProvider><Suspense fallback={<div className="page-loading" role="status">Opening Boafo…</div>}><RouterProvider router={router}/></Suspense></ThemeProvider>;}
